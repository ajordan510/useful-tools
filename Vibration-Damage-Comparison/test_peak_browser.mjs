import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const require=createRequire(import.meta.url),{chromium}=require('playwright');
const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[],network=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
const settle=()=>page.waitForFunction(()=>!busy&&!exportBusy);
const run=async()=>{await page.click('#run');await settle();};
await page.goto(new URL('vibration_damage_comparison.html',import.meta.url).href);
await page.click('#referenceCase');await settle();
const fixed=await page.evaluate(()=>({peak:last.r.inspect.peakRandom,fatigue:last.r.worst.margin}));
await page.fill('#peakFactor','');await page.selectOption('#peakMode','extreme');await run();
assert.equal(await page.evaluate(()=>last.r.worst.margin),fixed.fatigue);
const first=await page.evaluate(()=>last.r.inspect.peakRandom);
await page.fill('#peakProbability','99.99');assert.equal(await page.evaluate(()=>last),null);assert.equal(await page.locator('#csv').isDisabled(),true);await run();
assert.ok(await page.evaluate(()=>last.r.inspect.peakRandom)>first);
await page.fill('#peakProbability','100');await run();assert.equal(await page.evaluate(()=>last),null);assert.match(await page.locator('#status').innerText(),/probability/i);
await page.fill('#peakProbability','99');await page.fill('#duration','0.001');await run();
assert.equal(await page.evaluate(()=>last),null);assert.match(await page.locator('#status').innerText(),/100 expected response cycles/);
await page.fill('#duration','0.5');await run();assert.ok(await page.evaluate(()=>!!last));
// An old case imported while viewing the optional model must revert to fixed k.
await page.setInputFiles('#loadCase',fileURLToPath(new URL('reference/irvine-2011-case.json',import.meta.url)));
await page.waitForFunction(()=>document.querySelector('#peakMode').value==='fixed');await run();
assert.equal(await page.evaluate(()=>last.r.inspect.peakRandom),fixed.peak);
assert.equal(await page.locator('#peakProbability').isDisabled(),true);assert.equal(await page.locator('#peakFactor').isEnabled(),true);
await page.selectOption('#peakMode','extreme');await run();
await page.setViewportSize({width:390,height:844});assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
const dir=new URL('_paper_build/peak-research/',import.meta.url);fs.mkdirSync(dir,{recursive:true});
await page.locator('#peakMode').scrollIntoViewIfNeeded();await page.screenshot({path:fileURLToPath(new URL('optional-inputs-mobile.png',dir))});
assert.deepEqual(errors,[]);assert.deepEqual(network,[]);await browser.close();
console.log('PASS peak browser: probability changes invalidate results; high-probability and short-duration validation; fixed legacy import from optional mode; mobile; no network or runtime errors.');
